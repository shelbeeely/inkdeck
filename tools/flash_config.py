# PlatformIO pre-build script: bakes flash-config.txt (and the firmware
# version) into the firmware.
#
# flash-config.txt (git-ignored) uses the same "key = value" lines as
# /inkdeck.txt on the SD card, e.g.
#
#   repo_url = https://github.com/you/journal
#   git_token = github_pat_...
#   wifi_ssid = MyNetwork
#   wifi_password = secret
#   timezone = PST8PDT,M3.2.0,M11.1.0
#
# Environment variables INKDECK_<KEY> (e.g. INKDECK_REPO_URL, INKDECK_GIT_TOKEN)
# are appended after the file, so they win. The result is written to a
# generated FlashConfig.h as kFlashConfig; /inkdeck.txt still overrides it on
# the device.

import os
import subprocess

Import("env")  # noqa: F821  (provided by PlatformIO)

KEYS = [
    "wifi_ssid",
    "wifi_password",
    "timezone",
    "notes_folder",
    "journal_subfolder",
    "repo_url",
    "branch",
    "git_token",
]
SECRET_KEYS = {"wifi_password", "git_token"}

project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
source = os.environ.get("INKDECK_FLASH_CONFIG", os.path.join(project_dir, "flash-config.txt"))

lines = []
if os.path.isfile(source):
    with open(source, encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\r\n")
            stripped = line.strip()
            if not stripped or stripped.startswith("#") or "=" not in stripped:
                continue
            lines.append(stripped)
for key in KEYS:
    value = os.environ.get("INKDECK_" + key.upper())
    if value:
        lines.append(f"{key} = {value}")


def c_string(text):
    out = []
    for byte in text.encode("utf-8"):
        ch = chr(byte)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif 32 <= byte < 127:
            out.append(ch)
        else:
            out.append(f"\\{byte:03o}")  # octal: never swallows a following digit
    return '"' + "".join(out) + '"'


def firmware_version():
    # INKDECK_VERSION (set by the web flasher build), else the git commit.
    version = os.environ.get("INKDECK_VERSION")
    if version:
        return version
    try:
        return subprocess.run(
            ["git", "describe", "--tags", "--always", "--dirty"],
            cwd=project_dir, capture_output=True, text=True, check=True,
        ).stdout.strip() or "dev"
    except (OSError, subprocess.CalledProcessError):
        return "dev"


body = "\n".join(lines) + ("\n" if lines else "")
header = (
    "// Generated by tools/flash_config.py from flash-config.txt. Do not edit or commit.\n"
    "#pragma once\n"
    f"static const char kFlashConfig[] = {c_string(body)};\n"
    f"static const char kInkDeckVersion[] = {c_string(firmware_version())};\n"
)

out_dir = os.path.join(env.subst("$PROJECT_BUILD_DIR"), "flash_config")  # noqa: F821
os.makedirs(out_dir, exist_ok=True)
out_path = os.path.join(out_dir, "FlashConfig.h")
old = None
if os.path.isfile(out_path):
    with open(out_path, encoding="utf-8") as f:
        old = f.read()
if old != header:  # only touch it on change, so unrelated builds stay incremental
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(header)
env.Append(CPPPATH=[out_dir])  # noqa: F821

if lines:
    shown = []
    for line in lines:
        key, _, value = line.partition("=")
        key, value = key.strip(), value.strip()
        shown.append(f"{key}={'(set)' if key in SECRET_KEYS and value else value}")
    print("InkDeck flash config: " + ", ".join(shown))
else:
    print("InkDeck flash config: none (add flash-config.txt to bake in settings)")
