"""PlatformIO pre-build script: compiles prompts/library.txt into the firmware.

Writes .pio/build/<env>/prompts/PromptLibrary.h with the library text (comment
lines dropped) as one string; src/Prompts.cpp parses it at run time with the
same code that reads the user's own prompts file from the SD card.
"""

import os

Import("env")  # noqa: F821

project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
src = os.path.join(project_dir, "prompts", "library.txt")
with open(src, encoding="utf-8") as f:
    lines = [line.rstrip("\n") for line in f if line.strip() and not line.startswith("#")]
text = "\n".join(lines) + "\n"


def c_string(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append('\\n"\n    "')
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.extend(f"\\{b:03o}" for b in ch.encode("utf-8"))  # octal: never swallows a following digit
    return '"' + "".join(out) + '"'


header = (
    "// Generated by tools/prompts_header.py from prompts/library.txt. Do not edit.\n"
    "#pragma once\n"
    f"static const char kPromptLibrary[] =\n    {c_string(text)};\n"
)
out_dir = os.path.join(env.subst("$PROJECT_BUILD_DIR"), "prompts")  # noqa: F821
os.makedirs(out_dir, exist_ok=True)
out_path = os.path.join(out_dir, "PromptLibrary.h")
old = None
if os.path.isfile(out_path):
    with open(out_path, encoding="utf-8") as f:
        old = f.read()
if old != header:
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(header)
env.Append(CPPPATH=[out_dir])  # noqa: F821
print(f"InkDeck prompts: {sum(1 for l in lines if not l.startswith('@'))} prompts, {len(text)} bytes")
